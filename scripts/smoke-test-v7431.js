const assert=require('assert');
const fs=require('fs');
const os=require('os');
const path=require('path');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'alone-v7431-'));
process.env.ALONE_BASE_DIR=tmp;
fs.mkdirSync(path.join(tmp,'data'),{recursive:true});
const settings=require('../codigo-fonte-dev/server/settings');
const db=require('../codigo-fonte-dev/server/db');
const ops=require('../codigo-fonte-dev/server/ops');
const safety=require('../codigo-fonte-dev/server/safety-engine');
const policy=require('../codigo-fonte-dev/server/outbound-policy');
let s=settings.saveSettings({accountProtectionMode:'off',outboundAutomationMode:'automatic',safetyMaxAutomatedInitiationsPerHour:20,safetyMaxAutomatedInitiationsPerDay:2,safetyRestrictionCooldownHours:48});
const c=db.upsertContact('5511999911111','Cliente');
db.setConsent(c.id,'opted_in','manual');
db.setConsentCategory(c.id,'marketing','opted_in','manual');
db.touchInbound(c.id);
let d=policy.check({settings:s,contact:db.getContactById(c.id),kind:'campaign',source:'prospeccao:1'});
assert.strictEqual(d.allowed,true);
db.addActivity(c.id,'prospect_sent',{campaign_id:1});
db.addActivity(c.id,'proactive_followup_sent',{scenario:'hot'});
d=policy.check({settings:s,contact:db.getContactById(c.id),kind:'campaign',source:'prospeccao:1'});
assert.strictEqual(d.allowed,false);assert.strictEqual(d.reason,'daily_automation_limit');
s=settings.saveSettings({safetyMaxAutomatedInitiationsPerDay:40});
ops.audit('whatsapp_restriction_suspected',{resource:'whatsapp',details:{code:429,message:'rate limit'}});
d=policy.check({settings:s,contact:db.getContactById(c.id),kind:'proactive',source:'proatividade:hot',humanApproved:true});
assert.strictEqual(d.allowed,false);assert.strictEqual(d.reason,'restriction_cooldown');
const health=safety.calculateHealth(s);assert.strictEqual(health.recentRestriction,true);assert(health.lastRestrictionAt);assert.strictEqual(health.cooldownHours,48);
const html=fs.readFileSync(path.join(__dirname,'..','public','index.html'),'utf8');for(const id of ['safetyMaxAutomatedInitiationsPerDay','safetyRestrictionCooldownHours'])assert(html.includes(`id="${id}"`),`UI ausente: ${id}`);
db.flush();
console.log('Smoke v7.4.31 OK',{dailyLimit:true,restrictionCooldown:true,approvalRevalidation:true,score:health.score});
process.on('exit',()=>{try{fs.rmSync(tmp,{recursive:true,force:true});}catch(_){}});
